import json
ALL=["ALL"]
R={ # race: (key,name,short,W1,W2n,W3,W4)
 'F':('SBF','Federation Starbase','Fed SB'),
 'K':('SBK','Klingon Starbase','Kli SB'),
 'Z':('SBZ','Kzinti Starbase','Kzi SB'),
 'G':('SBG','Gorn Starbase','Gor SB'),
 'R':('SBR','Romulan Starbase','Rom SB')}
LET='ABCDEFGHJKLM'
def spec(r):
    ph=[{"t":"P4","arcs":ALL}]*12+[{"t":"P3","arcs":ALL}]*6   # Ph-4 x12, W2 = Ph-3 x6 (Ph-G is later than Y168)
    o=dict(tubes=None,ntube=0,dis=None,plas=[],drone=0,add=0)
    if r=='F': o.update(tubes=ALL,ntube=12,drone=6,add=6)
    if r=='K': o.update(dis=ALL,ndis=12,drone=6,add=6)
    if r=='Z': o.update(drone=12,add=6,dis=ALL,ndis=6)
    if r in 'GR':
        o['plas']=[{"t":t,"arcs":ALL} for _ in range(6) for t in 'RF']
        ph=ph+[{"t":"P3","arcs":ALL}]*6   # W3 Plasma-D racks: not built; the pre-Y165 360-degree Ph-3 stands in (R1.1A note)
    o['ph']=ph
    return o
def layout(r,o):
    g=[];box=lambda x,y:[x,y]
    # ---- flow layout of the core
    CX=1400;PER=16;y=440;groups=[]   # groups: (kind,name,count,labels,refit)
    def grid(x0,y0,cols,n,rowoff=0):
        return [[x0+(i%cols)*32,y0+(i//cols)*32] for i in range(n)]
    sysl=[('Sensor',12),('Scanner',12),('Damage Control',16),('Excess Damage',16),('Bridge',6),('Aux Control',6),('Probe',4),('Battery',24),('Trans',12),('Tractor',12),('Shuttle',12),('C Hull',36),('Armor',16),('APR',88),('Cargo',208)]
    if o['drone']:sysl.insert(6,('Drone',o['drone']))
    if o['add']:sysl.insert(6,('Add',o['add']))
    ycur=y;sysbox={}
    for n,c in sysl:
        sysbox[n]=grid(CX,ycur+16,PER,c);ycur+=16+((c+PER-1)//PER)*32+30
        if n=='Armor':  # refit armour groups follow
            sysbox['Armor+170']=grid(CX,ycur-14,PER,8);ycur+=((8+PER-1)//PER)*32+26
            sysbox['Armor+175']=grid(CX,ycur-14,PER,8);ycur+=((8+PER-1)//PER)*32+26
    # weapons
    wy=ycur+10;W={}
    ph=o['ph'];W['ph']=(grid(CX,wy,PER,len(ph)),["Ph-%d #%d"%(4 if p['t']=='P4' else 3,i+1) for i,p in enumerate(ph)]);wy+=((len(ph)+PER-1)//PER)*32+20
    if o['ntube']:W['pt']=(grid(CX,wy,PER,12),["Photon "+LET[i] for i in range(12)]);wy+=3*32+20 if False else 2*32+20
    if o.get('ndis'):
        n=o['ndis'];W['ds']=(grid(CX,wy,PER,n),["Disruptor "+LET[i] for i in range(n)]);wy+=((n+PER-1)//PER)*32+20
    if o['plas']:
        W['pl']=(grid(CX,wy,PER,12),["Plasma-%s %s"%(q['t'],LET[i]) for i,q in enumerate(o['plas'])]);wy+=2*32+20
    Yc=wy;yb=Yc+10
    # shields
    def shield(k,x0,y0):
        base=grid(x0,y0,10,50);a=[[x0+(i%10)*32,y0+160+(i//10)*32] for i in range(20)];b=[[x0+(i%10)*32,y0+224+(i//10)*32] for i in range(10)]
        return base,a,b
    pos={0:(CX,120),1:(1960,440),2:(1960,Yc-256),3:(CX,yb),4:(1000,Yc-256),5:(1000,440)}
    sb=[shield(k,*pos[k]) for k in range(6)]
    G=[]
    for k in range(6):G.append(["s",k,None,sb[k][0]])
    for k in range(6):G.append(["s",k,None,sb[k][1],1])
    for k in range(6):G.append(["s",k,None,sb[k][2],1])
    i170=list(range(6,12));i175=list(range(12,18))
    for n,c in sysl:
        G.append(["y",n,None,sysbox[n]])
        if n=='Armor':
            i170.append(len(G));G.append(["y","Armor",None,sysbox['Armor+170'],1])
            i175.append(len(G));G.append(["y","Armor",None,sysbox['Armor+175'],1])
    for k in ('ph','pt','ds','pl'):
        if k in W:G.append(["w",k,W[k][1],W[k][0]])
    outl=[[[CX-30,430],[CX+PER*32+20,430],[CX+PER*32+20,Yc-10],[CX-30,Yc-10]]]
    return {"g":G,"o":outl},i170,i175
out=["// [R1.1] Starbases (SB). Generated by sbgen.py from the Starbase SSD (Captain's Basic Set SSD book p.24) and the W1 to W4 table of R1.1A. The SSD sheet layout is synthetic (one flat list of boxes per system, not the six drawn modules)."]
refits={}
for r,(key,name,sh) in R.items():
    o=spec(r)
    s={"side":"bas","name":name,"short":sh,"cat":"E","size":1,"mc":1,"bd":6,"ls":3,"shc":[2,5],"pv":600,"ex":30,"base":1,"noDA":1,"rot":4,"phasers":o['ph'],"tubes":o['tubes'],"ntube":o['ntube'],"dis":o['dis'],"shields":[50]*6,
      "sys":{"Sensor":12,"Scanner":12,"Damage Control":16,"Bridge":6,"Aux Control":6,"Probe":4,"Battery":24,"Trans":12,"C Hull":36,"Cargo":208,"Armor":16,"Shuttle":12,"Tractor":12,"APR":88},
      "trk":{"Sensor":[6,6,6,6,5,5,4,4,3,2,1,0],"Scanner":[0,0,0,0,1,1,2,3,3,5,7,9],"Damage Control":[12,12,12,10,10,10,8,8,8,6,6,4,4,2,2,0]}}
    if o.get('ndis'):s['ndis']=o['ndis'];s['dmax']=30
    if o['plas']:s['plas']=o['plas']
    if o['drone']:s['sys']['Drone']=o['drone']
    if o['add']:s['sys']['Add']=o['add']
    geo,i170,i175=layout(r,o)
    out.append("SHIPS.%s=%s;"%(key,json.dumps(s,separators=(',',':'))))
    out.append("const GEO_%s=%s;"%(key,json.dumps(geo,separators=(',',':'))))
    refits[key]=(i170,i175)
out.append("['SBF','SBK','SBZ','SBG','SBR'].forEach(mkDef);")
out.append("const SBR_REFITS=%s;"%json.dumps(refits,separators=(',',':')))
open(__import__('os').path.join(__import__('os').path.dirname(__import__('os').path.abspath(__file__)),'..','src','data','starbase.js'),'w').write('\n'.join(out)+'\n')
